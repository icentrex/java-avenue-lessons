package codewars;

public class Task4 {

    /*
    Very simple, given a number, find its opposite (additive inverse).

    Examples:
    1: -1
    14: -14
    -34: 34
     */
    public static int opposite(int number)
    {
        return -1 * number;
    }

    public static void main(String[] args) {
        System.out.println(opposite(0));
    }
}
